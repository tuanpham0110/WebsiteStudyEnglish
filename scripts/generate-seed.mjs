// Generates supabase/migrations/20261010000002_seed_content.sql from content/*.mjs.
// The SQL is idempotent (upserts keyed by slug/id), so it can be re-run safely.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { vocabulary } from '../content/vocabulary.mjs';
import { grammarLessons } from '../content/grammar.mjs';
import { readingLessons } from '../content/reading.mjs';
import { listeningLessons } from '../content/listening.mjs';
import { pronunciationLessons, placementQuestions } from '../content/pronunciation-placement.mjs';

const OUT = fileURLToPath(new URL('../supabase/migrations/20261010000002_seed_content.sql', import.meta.url));
const LEVELS = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2'];

const q = (value) => (value === null || value === undefined ? 'null' : `'${String(value).replaceAll("'", "''")}'`);
const j = (value) => `${q(JSON.stringify(value))}::jsonb`;
const slugify = (text) =>
  text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 100);

function check(condition, message) {
  if (!condition) throw new Error(`Content error: ${message}`);
}

const lines = [
  '-- GENERATED by scripts/generate-seed.mjs from content/*.mjs — do not edit by hand.',
  '-- Original learning content for EnglishAI. Safe to re-run (upserts).',
  '',
];

// ------------------------------------------------------------------ vocabulary
const slugs = new Set();
const vocabRows = vocabulary.map(([word, pos, ipa, vi, def, exEn, exVi, level, topic]) => {
  check(LEVELS.includes(level), `bad level for ${word}`);
  const slug = slugify(`${word}-${pos}`);
  check(!slugs.has(slug), `duplicate vocabulary ${slug}`);
  slugs.add(slug);
  return `  (${[q(slug), q(word), q(pos), q(ipa), q(vi), q(def), q(exEn), q(exVi), q(level), q(topic)].join(', ')})`;
});
lines.push(
  'insert into public.vocabulary (slug, word, part_of_speech, ipa, meaning_vi, definition_en, example_en, example_vi, level, topic) values',
  vocabRows.join(',\n'),
  'on conflict (slug) do update set word = excluded.word, part_of_speech = excluded.part_of_speech, ipa = excluded.ipa,',
  '  meaning_vi = excluded.meaning_vi, definition_en = excluded.definition_en, example_en = excluded.example_en,',
  '  example_vi = excluded.example_vi, level = excluded.level, topic = excluded.topic;',
  '',
);

// ------------------------------------------------------------------ lessons & exercises
const lessonRows = [];
const exerciseRows = [];

const TYPE = { mc: 'multiple_choice', fill: 'fill_blank', reorder: 'reorder', fix: 'error_correction' };

grammarLessons.forEach((lesson, index) => {
  check(LEVELS.includes(lesson.level), `bad level ${lesson.id}`);
  lessonRows.push([
    lesson.id,
    'grammar',
    lesson.level,
    lesson.topic,
    lesson.title,
    lesson.titleVi,
    lesson.summary,
    {
      explanationVi: lesson.explanationVi,
      explanationEn: lesson.explanationEn,
      structure: lesson.structure,
      examples: lesson.examples,
      tips: lesson.tips ?? [],
    },
    index,
  ]);
  lesson.exercises.forEach((ex, i) => {
    const type = TYPE[ex.type];
    check(type, `bad exercise type in ${lesson.id}`);
    let data = {};
    let answer;
    let prompt = ex.prompt ?? '';
    if (ex.type === 'mc') {
      check(ex.answer >= 0 && ex.answer < ex.options.length, `answer index ${lesson.id}#${i}`);
      data = { options: ex.options };
      answer = { index: ex.answer };
    } else if (ex.type === 'reorder') {
      prompt = 'Sắp xếp các từ thành câu đúng.';
      data = { tokens: ex.tokens };
      answer = { sentence: ex.answer };
      const words = (s) => s.toLowerCase().split(/\s+/).filter(Boolean).sort().join(' ');
      check(words(ex.tokens.join(' ')) === words(ex.answer), `reorder tokens do not match answer in ${lesson.id}#${i}`);
    } else {
      answer = { accepted: ex.accepted };
    }
    exerciseRows.push([`${lesson.id}-${i + 1}`, lesson.id, type, lesson.level, prompt, data, answer, ex.vi ?? null, i]);
  });
});

readingLessons.forEach((lesson, index) => {
  lessonRows.push([
    lesson.id,
    'reading',
    lesson.level,
    lesson.topic,
    lesson.title,
    lesson.titleVi,
    lesson.summary,
    { passage: lesson.passage, summaryVi: lesson.summaryVi, wordCount: lesson.passage.split(/\s+/).length },
    index,
  ]);
  lesson.questions.forEach((qq, i) => {
    check(qq.answer >= 0 && qq.answer < qq.options.length, `answer index ${lesson.id}#${i}`);
    exerciseRows.push([`${lesson.id}-${i + 1}`, lesson.id, 'comprehension', lesson.level, qq.prompt, { options: qq.options }, { index: qq.answer }, null, i]);
  });
});

listeningLessons.forEach((lesson, index) => {
  lessonRows.push([
    lesson.id,
    'listening',
    lesson.level,
    lesson.topic,
    lesson.title,
    lesson.titleVi,
    lesson.summary,
    { script: lesson.script, summaryVi: lesson.summaryVi, dictation: lesson.dictation },
    index,
  ]);
  lesson.questions.forEach((qq, i) => {
    check(qq.answer >= 0 && qq.answer < qq.options.length, `answer index ${lesson.id}#${i}`);
    exerciseRows.push([`${lesson.id}-${i + 1}`, lesson.id, 'comprehension', lesson.level, qq.prompt, { options: qq.options }, { index: qq.answer }, null, i]);
  });
});

pronunciationLessons.forEach((lesson, index) => {
  lessonRows.push([
    lesson.id,
    'pronunciation',
    lesson.level,
    lesson.topic,
    lesson.title,
    lesson.titleVi,
    lesson.summary,
    { tipsVi: lesson.tipsVi, sentences: lesson.sentences },
    index,
  ]);
});

placementQuestions.forEach((qq, i) => {
  check(LEVELS.includes(qq.level), 'placement level');
  check(qq.answer >= 0 && qq.answer < qq.options.length, `placement answer #${i}`);
  exerciseRows.push([`placement-${i + 1}`, null, 'placement', qq.level, qq.prompt, { options: qq.options }, { index: qq.answer }, null, i]);
});

const ids = new Set();
for (const row of lessonRows) {
  check(/^[a-z0-9][a-z0-9-]{1,79}$/.test(row[0]), `lesson id ${row[0]}`);
  check(!ids.has(row[0]), `duplicate lesson ${row[0]}`);
  ids.add(row[0]);
}

lines.push(
  'insert into public.lessons (id, kind, level, topic, title, title_vi, summary, content, sort_order) values',
  lessonRows
    .map(([id, kind, level, topic, title, titleVi, summary, content, order]) =>
      `  (${[q(id), q(kind), q(level), q(topic), q(title), q(titleVi), q(summary), j(content), order].join(', ')})`,
    )
    .join(',\n'),
  'on conflict (id) do update set kind = excluded.kind, level = excluded.level, topic = excluded.topic, title = excluded.title,',
  '  title_vi = excluded.title_vi, summary = excluded.summary, content = excluded.content, sort_order = excluded.sort_order;',
  '',
  'insert into public.exercises (id, lesson_id, type, level, prompt, data, answer, explanation_vi, sort_order) values',
  exerciseRows
    .map(([id, lessonId, type, level, prompt, data, answer, vi, order]) =>
      `  (${[q(id), q(lessonId), q(type), q(level), q(prompt), j(data), j(answer), q(vi), order].join(', ')})`,
    )
    .join(',\n'),
  'on conflict (id) do update set lesson_id = excluded.lesson_id, type = excluded.type, level = excluded.level, prompt = excluded.prompt,',
  '  data = excluded.data, answer = excluded.answer, explanation_vi = excluded.explanation_vi, sort_order = excluded.sort_order;',
  '',
  '-- Remove exercises that no longer exist in the content files (attempts keep their rows; exercise_id becomes null).',
  `delete from public.exercises where id not in (${exerciseRows.map((r) => q(r[0])).join(', ')});`,
  '',
);

writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`Wrote ${OUT}\n  vocabulary: ${vocabRows.length}\n  lessons: ${lessonRows.length}\n  exercises: ${exerciseRows.length}`);
