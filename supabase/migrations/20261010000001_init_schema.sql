-- Dashboard aggregates computed from the user's real activity.
create or replace function public.get_dashboard_stats(p_tz text default 'UTC')
returns jsonb
language plpgsql
stable
security invoker
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_tz text := 'UTC';
  v_today date;
  v_days date[];
  v_cursor date;
  v_streak int := 0;
  v_result jsonb;
begin
  if v_uid is null then
    raise exception 'not authenticated' using errcode = '42501';
  end if;
  if p_tz is not null and exists (select 1 from pg_catalog.pg_timezone_names where name = p_tz) then
    v_tz := p_tz;
  end if;
  v_today := (now() at time zone v_tz)::date;

  select coalesce(array_agg(d order by d desc), '{}') into v_days
    from (
      select distinct (occurred_at at time zone v_tz)::date as d
        from public.learning_progress
       where user_id = v_uid and occurred_at > now() - interval '400 days'
    ) s;

  if v_today = any (v_days) then
    v_cursor := v_today;
  elsif (v_today - 1) = any (v_days) then
    v_cursor := v_today - 1;
  end if;
  while v_cursor is not null and v_cursor = any (v_days) loop
    v_streak := v_streak + 1;
    v_cursor := v_cursor - 1;
  end loop;

  select jsonb_build_object(
    'timezone', v_tz,
    'streak_days', v_streak,
    'total_seconds', (select coalesce(sum(duration_seconds), 0) from public.learning_progress where user_id = v_uid),
    'today_seconds', (
      select coalesce(sum(duration_seconds), 0) from public.learning_progress
       where user_id = v_uid and (occurred_at at time zone v_tz)::date = v_today
    ),
    'week_seconds', (
      select coalesce(sum(duration_seconds), 0) from public.learning_progress
       where user_id = v_uid and (occurred_at at time zone v_tz)::date > v_today - 7
    ),
    'words_total', (select count(*) from public.user_vocabulary where user_id = v_uid),
    'words_mastered', (select count(*) from public.user_vocabulary where user_id = v_uid and status = 'mastered'),
    'words_due', (select count(*) from public.user_vocabulary where user_id = v_uid and due_at <= now() and status <> 'mastered'),
    'exercises_total', (select count(*) from public.exercise_attempts where user_id = v_uid and skill <> 'placement'),
    'exercises_correct', (select count(*) from public.exercise_attempts where user_id = v_uid and skill <> 'placement' and is_correct),
    'speaking_sessions', (
      select count(*) from public.speaking_sessions
       where user_id = v_uid and status in ('completed', 'expired') and coalesce(duration_seconds, 0) > 0
    ),
    'speaking_seconds', (
      select coalesce(sum(duration_seconds), 0) from public.speaking_sessions where user_id = v_uid
    ),
    'conversations', (select count(*) from public.conversations where user_id = v_uid),
    'lessons_completed', (
      select count(distinct ref_id) from public.learning_progress
       where user_id = v_uid and completed and activity in ('grammar', 'reading', 'listening', 'pronunciation') and ref_id is not null
    ),
    'daily', (
      select coalesce(jsonb_agg(jsonb_build_object('day', g.day, 'seconds', coalesce(t.seconds, 0)) order by g.day), '[]'::jsonb)
        from (select (v_today - i) as day from generate_series(0, 13) as i) g
        left join (
          select (occurred_at at time zone v_tz)::date as day, sum(duration_seconds) as seconds
            from public.learning_progress
           where user_id = v_uid and occurred_at > now() - interval '15 days'
           group by 1
        ) t on t.day = g.day
    ),
    'by_activity', (
      select coalesce(jsonb_object_agg(activity, seconds), '{}'::jsonb)
        from (
          select activity, sum(duration_seconds) as seconds
            from public.learning_progress
           where user_id = v_uid and occurred_at > now() - interval '30 days'
           group by activity
        ) a
    ),
    'skill_accuracy', (
      select coalesce(jsonb_object_agg(skill, jsonb_build_object('total', total, 'correct', correct)), '{}'::jsonb)
        from (
          select skill, count(*) as total, count(*) filter (where is_correct) as correct
            from public.exercise_attempts
           where user_id = v_uid and skill <> 'placement' and created_at > now() - interval '30 days'
           group by skill
        ) s
    ),
    'recent', (
      select coalesce(jsonb_agg(r order by r.occurred_at desc), '[]'::jsonb)
        from (
          select activity, ref_id, duration_seconds, score, completed, occurred_at
            from public.learning_progress
           where user_id = v_uid
           order by occurred_at desc
           limit 12
        ) r
    )
  ) into v_result;

  return v_result;
end;
$$;

-- Today's usage for the signed-in user (UTC day, same window as the quota checks).
create or replace function public.get_my_usage_today()
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  select jsonb_build_object(
    'chat', coalesce(sum(units) filter (where kind = 'chat' and status = 'ok'), 0),
    'assist', coalesce(sum(units) filter (where kind = 'assist' and status = 'ok'), 0),
    'evaluation', coalesce(sum(units) filter (where kind = 'evaluation' and status = 'ok'), 0),
    'stt', coalesce(sum(units) filter (where kind = 'stt' and status = 'ok'), 0),
    'voice_sessions', coalesce(sum(units) filter (where kind = 'voice_session'), 0),
    'voice_seconds', coalesce(sum(units) filter (where kind = 'voice_seconds'), 0),
    'resets_at', (date_trunc('day', now() at time zone 'utc') + interval '1 day') at time zone 'utc'
  )
  from public.usage_logs
  where user_id = (select auth.uid())
    and created_at >= date_trunc('day', now() at time zone 'utc') at time zone 'utc';
$$;

-- Admin overview. SECURITY DEFINER with an explicit admin check; returns only
-- aggregates (no message content, no emails).
create or replace function public.admin_overview()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_day_start timestamptz := date_trunc('day', now() at time zone 'utc') at time zone 'utc';
begin
  if not public.is_admin() then
    raise exception 'forbidden' using errcode = '42501';
  end if;

  return jsonb_build_object(
    'users_total', (select count(*) from public.profiles),
    'users_new_7d', (select count(*) from public.profiles where created_at > now() - interval '7 days'),
    'users_onboarded', (select count(*) from public.profiles where onboarded_at is not null),
    'active_today', (select count(distinct user_id) from public.learning_progress where occurred_at >= v_day_start),
    'requests_today', (
      select coalesce(jsonb_object_agg(kind, n), '{}'::jsonb)
        from (select kind, sum(requests) as n from public.usage_logs
               where created_at >= v_day_start and kind in ('chat', 'assist', 'evaluation', 'stt', 'tts')
               group by kind) k
    ),
    'errors_today', (select count(*) from public.usage_logs where created_at >= v_day_start and status = 'error'),
    'voice_seconds_today', (
      select coalesce(sum(units), 0) from public.usage_logs where kind = 'voice_seconds' and created_at >= v_day_start
    ),
    'voice_active_now', (select count(*) from public.speaking_sessions where status = 'active' and transport = 'realtime'),
    'daily', (
      select coalesce(jsonb_agg(jsonb_build_object('day', g.day, 'requests', coalesce(u.requests, 0), 'voice_seconds', coalesce(v.seconds, 0)) order by g.day), '[]'::jsonb)
        from (select ((now() at time zone 'utc')::date - i) as day from generate_series(0, 13) as i) g
        left join (
          select (created_at at time zone 'utc')::date as day, sum(requests) as requests
            from public.usage_logs
           where created_at > now() - interval '15 days' and kind in ('chat', 'assist', 'evaluation', 'stt', 'tts')
           group by 1
        ) u on u.day = g.day
        left join (
          select (created_at at time zone 'utc')::date as day, sum(units) as seconds
            from public.usage_logs
           where created_at > now() - interval '15 days' and kind = 'voice_seconds'
           group by 1
        ) v on v.day = g.day
    ),
    'top_users_today', (
      select coalesce(jsonb_agg(t order by t.requests desc), '[]'::jsonb)
        from (
          select left(u.user_id::text, 8) as user_ref, max(p.display_name) as display_name, sum(u.requests) as requests
            from public.usage_logs u
            left join public.profiles p on p.id = u.user_id
           where u.created_at >= v_day_start and u.user_id is not null
           group by u.user_id
           order by sum(u.requests) desc
           limit 10
        ) t
    ),
    'content', jsonb_build_object(
      'lessons', (select count(*) from public.lessons),
      'exercises', (select count(*) from public.exercises),
      'vocabulary', (select count(*) from public.vocabulary where owner_id is null)
    )
  );
end;
$$;

