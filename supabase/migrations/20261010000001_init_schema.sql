-- =========================================================================
-- Helpers
-- =========================================================================
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- =========================================================================
-- profiles
-- =========================================================================
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text check (char_length(display_name) <= 80),
  level text not null default 'A2' check (level in ('A1', 'A2', 'B1', 'B2', 'C1', 'C2')),
  role text not null default 'user' check (role in ('user', 'admin')),
  onboarded_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create trigger profiles_updated_at before update on public.profiles
  for each row execute function public.set_updated_at();

-- =========================================================================
-- learning_preferences
-- =========================================================================
create table public.learning_preferences (
  user_id uuid primary key references public.profiles (id) on delete cascade,
  goals text[] not null default '{}'
    check (goals <@ array['communication', 'work', 'travel', 'exam', 'study', 'interview', 'daily_life']::text[]),
  daily_minutes int not null default 15 check (daily_minutes between 5 and 240),
  explanation_language text not null default 'vi' check (explanation_language in ('vi', 'en')),
  focus_skills text[] not null default '{}'
    check (focus_skills <@ array['speaking', 'listening', 'reading', 'writing', 'vocabulary', 'grammar', 'pronunciation']::text[]),
  placement_level text check (placement_level in ('A1', 'A2', 'B1', 'B2', 'C1', 'C2')),
  placement_score int check (placement_score between 0 and 100),
  updated_at timestamptz not null default now()
);
create trigger learning_preferences_updated_at before update on public.learning_preferences
  for each row execute function public.set_updated_at();

-- =========================================================================
-- learning_plans (generated by rule-based recommendation logic)
-- =========================================================================
create table public.learning_plans (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  level text not null check (level in ('A1', 'A2', 'B1', 'B2', 'C1', 'C2')),
  title text not null check (char_length(title) between 1 and 200),
  items jsonb not null default '[]'::jsonb
    check (jsonb_typeof(items) = 'array' and pg_column_size(items) < 20000),
  source text not null default 'rules' check (source in ('rules')),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
create index learning_plans_user_idx on public.learning_plans (user_id, created_at desc);

-- =========================================================================
-- Shared learning content: lessons, exercises, vocabulary catalog
-- =========================================================================
create table public.lessons (
  id text primary key check (id ~ '^[a-z0-9][a-z0-9-]{1,79}$'),
  kind text not null check (kind in ('grammar', 'reading', 'listening', 'pronunciation')),
  level text not null check (level in ('A1', 'A2', 'B1', 'B2', 'C1', 'C2')),
  topic text not null check (char_length(topic) <= 60),
  title text not null check (char_length(title) <= 160),
  title_vi text check (char_length(title_vi) <= 160),
  summary text check (char_length(summary) <= 500),
  content jsonb not null default '{}'::jsonb,
  sort_order int not null default 0,
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index lessons_kind_level_idx on public.lessons (kind, level, sort_order);
create trigger lessons_updated_at before update on public.lessons
  for each row execute function public.set_updated_at();

create table public.exercises (
  id text primary key check (id ~ '^[a-z0-9][a-z0-9-]{1,99}$'),
  lesson_id text references public.lessons (id) on delete cascade,
  type text not null check (type in (
    'multiple_choice', 'fill_blank', 'reorder', 'error_correction', 'comprehension', 'dictation', 'placement'
  )),
  level text check (level in ('A1', 'A2', 'B1', 'B2', 'C1', 'C2')),
  prompt text not null check (char_length(prompt) <= 2000),
  data jsonb not null default '{}'::jsonb,
  answer jsonb not null,
  explanation_vi text check (char_length(explanation_vi) <= 2000),
  explanation_en text check (char_length(explanation_en) <= 2000),
  sort_order int not null default 0
);
create index exercises_lesson_idx on public.exercises (lesson_id, sort_order);
create index exercises_type_idx on public.exercises (type, level);

-- owner_id IS NULL  -> shared catalog word (seeded, read-only for users)
-- owner_id = user   -> personal word created by that user (full CRUD for the owner)
create table public.vocabulary (
  id uuid primary key default gen_random_uuid(),
  slug text unique check (slug ~ '^[a-z0-9][a-z0-9-]{0,99}$'),
  owner_id uuid references public.profiles (id) on delete cascade,
  word text not null check (char_length(btrim(word)) between 1 and 80),
  part_of_speech text check (char_length(part_of_speech) <= 30),
  ipa text check (char_length(ipa) <= 80),
  meaning_vi text not null check (char_length(btrim(meaning_vi)) between 1 and 300),
  definition_en text check (char_length(definition_en) <= 500),
  example_en text check (char_length(example_en) <= 500),
  example_vi text check (char_length(example_vi) <= 500),
  level text check (level in ('A1', 'A2', 'B1', 'B2', 'C1', 'C2')),
  topic text check (char_length(topic) <= 40),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint vocabulary_catalog_has_slug check (owner_id is not null or slug is not null)
);
create index vocabulary_owner_idx on public.vocabulary (owner_id);
create index vocabulary_catalog_idx on public.vocabulary (level, topic) where owner_id is null;
create index vocabulary_word_idx on public.vocabulary (lower(word));
create trigger vocabulary_updated_at before update on public.vocabulary
  for each row execute function public.set_updated_at();

