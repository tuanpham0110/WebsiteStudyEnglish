-- Atomically check per-user daily limit, per-user per-minute rate and the
-- whole-app daily cap, then record the usage. Returns {allowed, reason, ...}.
create or replace function public.consume_ai_quota(
  p_user uuid,
  p_kind text,
  p_units int,
  p_requests int,
  p_user_daily_limit int,
  p_user_minute_limit int,
  p_global_daily_limit int,
  p_provider text default null,
  p_model text default null,
  p_meta jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_day_start timestamptz := date_trunc('day', now() at time zone 'utc') at time zone 'utc';
  v_user_today int;
  v_user_minute int;
  v_global_today int;
  v_id bigint;
begin
  if p_kind not in ('chat', 'assist', 'evaluation', 'stt', 'tts') then
    raise exception 'invalid kind %', p_kind using errcode = '22023';
  end if;
  if p_units < 1 or p_requests < 1 then
    raise exception 'invalid units' using errcode = '22023';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('quota:' || p_user::text, 0));

  select coalesce(sum(units), 0) into v_user_today
    from public.usage_logs
   where user_id = p_user and kind = p_kind and status = 'ok' and created_at >= v_day_start;
  if v_user_today + p_units > p_user_daily_limit then
    return jsonb_build_object('allowed', false, 'reason', 'user_daily', 'used', v_user_today, 'limit', p_user_daily_limit);
  end if;

  select count(*) into v_user_minute
    from public.usage_logs
   where user_id = p_user
     and kind in ('chat', 'assist', 'evaluation', 'stt', 'tts', 'voice_session')
     and created_at >= now() - interval '1 minute';
  if v_user_minute >= p_user_minute_limit then
    return jsonb_build_object('allowed', false, 'reason', 'rate_limited', 'used', v_user_today, 'limit', p_user_daily_limit);
  end if;

  perform pg_advisory_xact_lock(hashtextextended('quota:global', 0));
  select coalesce(sum(requests), 0) into v_global_today
    from public.usage_logs
   where kind in ('chat', 'assist', 'evaluation', 'stt', 'tts') and created_at >= v_day_start;
  if v_global_today + p_requests > p_global_daily_limit then
    return jsonb_build_object('allowed', false, 'reason', 'global_daily', 'used', v_user_today, 'limit', p_user_daily_limit);
  end if;

  insert into public.usage_logs (user_id, kind, units, requests, provider, model, meta)
  values (p_user, p_kind, p_units, p_requests, p_provider, p_model, coalesce(p_meta, '{}'::jsonb))
  returning id into v_id;

  return jsonb_build_object(
    'allowed', true, 'log_id', v_id, 'used', v_user_today + p_units, 'limit', p_user_daily_limit
  );
end;
$$;

-- Mark a usage row as failed (the provider call errored). Failed rows do not
-- count toward the user's daily quota but still count for rate limiting and
-- the global cap (the provider request was still made).
create or replace function public.mark_usage_error(p_log_id bigint, p_code text)
returns void
language sql
security definer
set search_path = ''
as $$
  update public.usage_logs
     set status = 'error', meta = meta || jsonb_build_object('error', left(p_code, 60))
   where id = p_log_id;
$$;

-- Start a realtime voice session: enforce one active session per user, a daily
-- per-user voice budget, a global concurrency cap and a global daily budget.
create or replace function public.start_voice_session(
  p_user uuid,
  p_provider text,
  p_model text,
  p_level text,
  p_topic text,
  p_scenario text,
  p_session_seconds int,
  p_user_daily_seconds int,
  p_user_minute_limit int,
  p_global_daily_seconds int,
  p_global_concurrent int
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_day_start timestamptz := date_trunc('day', now() at time zone 'utc') at time zone 'utc';
  v_used int;
  v_remaining int;
  v_grant int;
  v_active int;
  v_global_used int;
  v_recent int;
  v_id uuid;
begin
  perform pg_advisory_xact_lock(hashtextextended('voice:' || p_user::text, 0));
  perform pg_advisory_xact_lock(hashtextextended('voice:global', 0));

  -- Sessions whose client never reported the end are closed at their full budget
  -- (and that budget is recorded as used).
  with expired as (
    update public.speaking_sessions
       set status = 'expired',
           ended_at = started_at + make_interval(secs => max_seconds),
           duration_seconds = max_seconds
     where status = 'active'
       and transport = 'realtime'
       and started_at + make_interval(secs => max_seconds + 120) < now()
    returning id, user_id, max_seconds, provider, model
  )
  insert into public.usage_logs (user_id, kind, units, requests, provider, model, meta)
  select user_id, 'voice_seconds', max_seconds, 0, provider, model, jsonb_build_object('session_id', id, 'expired', true)
    from expired;

  if exists (
    select 1 from public.speaking_sessions
     where user_id = p_user and status = 'active' and transport = 'realtime'
  ) then
    return jsonb_build_object('allowed', false, 'reason', 'session_active');
  end if;

  select count(*) into v_recent
    from public.usage_logs
   where user_id = p_user
     and kind in ('chat', 'assist', 'evaluation', 'stt', 'tts', 'voice_session')
     and created_at >= now() - interval '1 minute';
  if v_recent >= p_user_minute_limit then
    return jsonb_build_object('allowed', false, 'reason', 'rate_limited');
  end if;

  -- Usage comes from usage_logs, which users cannot delete (deleting a session's
  -- transcript must not refund its voice time).
  select coalesce(sum(units), 0) into v_used
    from public.usage_logs
   where user_id = p_user and kind = 'voice_seconds' and created_at >= v_day_start;
  v_remaining := p_user_daily_seconds - v_used;
  if v_remaining < 30 then
    return jsonb_build_object('allowed', false, 'reason', 'user_daily_voice', 'used_seconds', v_used, 'limit_seconds', p_user_daily_seconds);
  end if;
  v_grant := least(p_session_seconds, v_remaining);

  select count(*) into v_active
    from public.speaking_sessions
   where status = 'active' and transport = 'realtime';
  if v_active >= p_global_concurrent then
    return jsonb_build_object('allowed', false, 'reason', 'global_concurrent');
  end if;

  select coalesce((select sum(units) from public.usage_logs where kind = 'voice_seconds' and created_at >= v_day_start), 0)
       + coalesce((select sum(max_seconds) from public.speaking_sessions where status = 'active' and transport = 'realtime'), 0)
    into v_global_used;
  v_grant := least(v_grant, p_global_daily_seconds - v_global_used);
  if v_grant < 30 then
    return jsonb_build_object('allowed', false, 'reason', 'global_daily_voice');
  end if;

  insert into public.speaking_sessions (user_id, transport, provider, model, level, topic, scenario_id, max_seconds)
  values (p_user, 'realtime', p_provider, p_model, p_level, p_topic, p_scenario, v_grant)
  returning id into v_id;

  insert into public.usage_logs (user_id, kind, units, requests, provider, model, meta)
  values (p_user, 'voice_session', 1, 1, p_provider, p_model, jsonb_build_object('session_id', v_id));

  return jsonb_build_object(
    'allowed', true, 'session_id', v_id, 'max_seconds', v_grant,
    'used_seconds', v_used, 'limit_seconds', p_user_daily_seconds
  );
end;
$$;

-- Finish a session. Duration is measured by the server clock (never trusted
-- from the client) and capped at the granted budget.
create or replace function public.finish_speaking_session(
  p_user uuid,
  p_session uuid,
  p_status text,
  p_error_code text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row public.speaking_sessions%rowtype;
  v_duration int;
begin
  if p_status not in ('completed', 'failed') then
    raise exception 'invalid status' using errcode = '22023';
  end if;

  select * into v_row from public.speaking_sessions
   where id = p_session and user_id = p_user
   for update;
  if not found then
    return jsonb_build_object('ok', false, 'reason', 'not_found');
  end if;
  if v_row.status <> 'active' then
    return jsonb_build_object('ok', true, 'already_ended', true, 'duration_seconds', v_row.duration_seconds, 'status', v_row.status);
  end if;

  v_duration := least(
    greatest(0, floor(extract(epoch from (now() - v_row.started_at)))::int),
    case when v_row.transport = 'realtime' then v_row.max_seconds else 3600 end
  );

  update public.speaking_sessions
     set status = p_status, ended_at = now(), duration_seconds = v_duration, error_code = left(p_error_code, 60)
   where id = p_session;

  if v_row.transport = 'realtime' then
    insert into public.usage_logs (user_id, kind, units, requests, provider, model, meta)
    values (p_user, 'voice_seconds', v_duration, 0, v_row.provider, v_row.model, jsonb_build_object('session_id', p_session));
  end if;

  if v_duration > 0 then
    insert into public.learning_progress (user_id, activity, ref_id, duration_seconds, completed)
    values (
      p_user,
      case when v_row.scenario_id is not null then 'roleplay' else 'speaking' end,
      p_session::text,
      v_duration,
      p_status = 'completed'
    );
  end if;

  return jsonb_build_object('ok', true, 'duration_seconds', v_duration, 'status', p_status);
end;
$$;

